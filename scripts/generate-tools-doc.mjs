#!/usr/bin/env node
/**
 * Generate docs/TOOLS.md from tool registrations (SSOT: the code).
 * Run: node scripts/generate-tools-doc.mjs
 */
import { readdir, readFile, writeFile } from "fs/promises";
import path from "path";
import { fileURLToPath } from "url";

const TOOLS_DIR = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "src", "tools");
const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "docs", "TOOLS.md");

const dirEntries = await readdir(TOOLS_DIR);
const files = dirEntries.filter((f) => f.endsWith(".ts") && f !== "types.ts" && f !== "directory-helpers.ts" && !f.endsWith("-tools.ts"));
const extraFiles = ["undo-tools.ts", "server-stats-tools.ts", "file-tools.ts"].filter((f) => dirEntries.includes(f));
const allFiles = [...files, ...extraFiles];

const tools = [];
for (const f of allFiles) {
  const content = await readFile(path.join(TOOLS_DIR, f), "utf8");
  const re = /(?:destructive|standard|readOnly|idempotent)\(\s*\n?\s*"(\w+)",\s*\n?\s*\{\s*\n?\s*title:\s*"([^"]+)",\s*\n?\s*description:\s*([\s\S]*?),\s*\n?\s*inputSchema/g;
  let m;
  while ((m = re.exec(content))) {
    const descPart = m[3];
    const strings = [...descPart.matchAll(/"((?:[^"\\]|\\.)*)"/g)].map((s) => s[1]);
    tools.push({ name: m[1], title: m[2], description: strings.join(" ").replace(/\s+/g, " ").trim(), file: f });
  }
}

tools.sort((a, b) => a.name.localeCompare(b.name));

const byCategory = {};
for (const t of tools) {
  const cat = t.file.replace(/\.ts$/, "");
  byCategory[cat] = byCategory[cat] || [];
  byCategory[cat].push(t);
}

let md = `# Tools Reference\n\n<!-- AUTO-GENERATED by scripts/generate-tools-doc.mjs — do not edit manually -->\n\n${tools.length} tools registered.\n\n`;
for (const [cat, list] of Object.entries(byCategory).sort()) {
  md += `## ${cat}\n\n| Tool | Description |\n|---|---|\n`;
  for (const t of list) {
    md += `| \`${t.name}\` | ${t.description.replace(/\|/g, "\\|")} |\n`;
  }
  md += "\n";
}
await writeFile(OUT, md, "utf8");
console.log(`Wrote ${OUT} (${tools.length} tools)`);